"""InfluenceSphere Streamlit application."""

from __future__ import annotations

from pathlib import Path

import streamlit as st

from dashboard.pages.overview import render as render_overview
from src.config import load_config


BRAND = "InfluenceSphere — Large-Scale Social Network Intelligence Platform"


def _theme() -> None:
    st.markdown(
        """
        <style>
        :root { --is-accent: #65d6c3; --is-panel: #17212b; }
        .stApp { background: #0e151d; }
        [data-testid="stMetric"] {
            background: var(--is-panel);
            border: 1px solid #263746;
            border-radius: 12px;
            padding: 14px;
        }
        [data-testid="stMetricValue"] { color: var(--is-accent); }
        h1, h2, h3 { letter-spacing: -0.02em; }
        </style>
        """,
        unsafe_allow_html=True,
    )


def main() -> None:
    st.set_page_config(
        page_title="InfluenceSphere",
        page_icon="◎",
        layout="wide",
        initial_sidebar_state="expanded",
    )
    _theme()
    config = load_config()
    with st.sidebar:
        st.title("InfluenceSphere")
        st.caption("Large-Scale Social Network Intelligence Platform")
        page = st.radio("Navigate", ["Overview", "About / Methodology"])
        st.divider()
        st.caption(f"Results: `{config.paths.results}`")
    if page == "Overview":
        render_overview(Path(config.paths.results))
    else:
        st.title("About / Methodology")
        st.markdown(
            """
            InfluenceSphere summarizes graph structure and algorithm results
            generated by the reproducible Spark pipeline. Metrics shown here are
            read from persisted JSON, CSV, and Parquet artifacts only.

            PageRank and HITS operate on the directed graph. Label Propagation,
            triangles, and clustering use the undirected representation where
            documented. Triangle metrics are labeled exact or estimated using
            the persisted algorithm metadata; missing artifacts are never
            replaced with invented values.
            """
        )


if __name__ == "__main__":
    main()
